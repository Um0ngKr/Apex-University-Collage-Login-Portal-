    // -------------------------------------------------------------------------
    // Internal Lightweight PDF 1.4 Formatter
    // -------------------------------------------------------------------------

    private static class PdfDocument {
        private final List<String> lines = new ArrayList<>();
        private final String title;

        public PdfDocument(String title) {
            this.title = title;
        }

        public void addTitle(String text) {
            lines.add("T:" + text);
        }

        public void addSubTitle(String text) {
            lines.add("S:" + text);
        }

        public void addHeaderLine(String text) {
            lines.add("H:" + text);
        }

        public void addSeparator() {
            lines.add("LINE:");
        }

        public void addTextLine(String text) {
            lines.add("P:" + text);
        }

        public void addKeyValue(String key, String value) {
            lines.add("KV:" + key + " : " + value);
        }

        public void addTableHeader(String c1, String c2, String c3, String c4) {
            lines.add("TH4:" + pad(c1, 12) + pad(c2, 35) + pad(c3, 14) + pad(c4, 15));
        }

        public void addTableRow(String c1, String c2, String c3, String c4) {
            lines.add("TR4:" + pad(c1, 12) + pad(c2, 35) + pad(c3, 14) + pad(c4, 15));
        }

        public void addTableHeader5(String c1, String c2, String c3, String c4, String c5, String c6) {
            lines.add("TH5:" + pad(c1, 10) + pad(c2, 32) + pad(c3, 8) + pad(c4, 8) + pad(c5, 8) + pad(c6, 6));
        }

        public void addTableRow5(String c1, String c2, String c3, String c4, String c5, String c6) {
            lines.add("TR5:" + pad(c1, 10) + pad(c2, 32) + pad(c3, 8) + pad(c4, 8) + pad(c5, 8) + pad(c6, 6));
        }

        public void addFooter(String text) {
            lines.add("F:" + text);
        }

        private String pad(String s, int len) {
            if (s == null) s = "";
            if (s.length() > len) {
                return s.substring(0, len - 2) + "..";
            }
            StringBuilder sb = new StringBuilder(s);
            while (sb.length() < len) {
                sb.append(" ");
            }
            return sb.toString();
        }

        public byte[] build() {
            try {
                ByteArrayOutputStream out = new ByteArrayOutputStream();
                List<Integer> offsets = new ArrayList<>();

                // PDF Header
                write(out, "%PDF-1.4\n%\u00e2\u00e3\u00cf\u00d3\n");

                // Object 1: Catalog
                offsets.add(out.size());
                write(out, "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");

                // Object 2: Pages
                offsets.add(out.size());
                write(out, "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n");

                // Object 3: Page (A4 is 595 x 842 points)
                offsets.add(out.size());
                write(out, "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>\nendobj\n");

                // Object 4: Font Helvetica-Bold
                offsets.add(out.size());
                write(out, "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n");

                // Object 5: Font Courier / Helvetica
                offsets.add(out.size());
                write(out, "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n");

                // Build Content Stream
                StringBuilder stream = new StringBuilder();
                int y = 800;

                // Border Box
                stream.append("0.1 0.2 0.4 rg\n"); // Navy / Royal Blue
                stream.append("20 20 555 802 re S\n");
                stream.append("22 22 551 798 re S\n");

                for (String raw : lines) {
                    if (y < 60) break; // stay within page

                    if (raw.startsWith("T:")) {
                        // Title
                        stream.append("BT /F1 16 Tf 0.05 0.15 0.35 rg 297 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(2)))
                              .append(") Tj ET\n");
                        y -= 18;
                    } else if (raw.startsWith("S:")) {
                        // Subtitle
                        stream.append("BT /F1 9 Tf 0.3 0.3 0.3 rg 297 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(2)))
                              .append(") Tj ET\n");
                        y -= 16;
                    } else if (raw.startsWith("H:")) {
                        // Header badge
                        stream.append("0.1 0.25 0.55 rg\n");
                        stream.append("40 ").append(y - 4).append(" 515 20 re f\n");
                        stream.append("BT /F1 11 Tf 1 1 1 rg 50 ")
                              .append(y + 1)
                              .append(" Td (")
                              .append(escape(raw.substring(2)))
                              .append(") Tj ET\n");
                        y -= 26;
                    } else if (raw.equals("LINE:")) {
                        // Separator line
                        stream.append("0.8 0.8 0.8 RG 40 ").append(y).append(" m 555 ").append(y).append(" l S\n");
                        y -= 14;
                    } else if (raw.startsWith("KV:")) {
                        // Key-Value
                        stream.append("BT /F2 9 Tf 0 0 0 rg 50 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(3)))
                              .append(") Tj ET\n");
                        y -= 14;
                    } else if (raw.startsWith("TH4:") || raw.startsWith("TH5:")) {
                        // Table header
                        stream.append("0.9 0.92 0.96 rg\n");
                        stream.append("45 ").append(y - 3).append(" 505 14 re f\n");
                        stream.append("BT /F1 8 Tf 0.1 0.2 0.4 rg 50 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(4)))
                              .append(") Tj ET\n");
                        y -= 16;
                    } else if (raw.startsWith("TR4:") || raw.startsWith("TR5:")) {
                        // Table row
                        stream.append("BT /F2 8 Tf 0.1 0.1 0.1 rg 50 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(4)))
                              .append(") Tj ET\n");
                        y -= 14;
                    } else if (raw.startsWith("F:")) {
                        // Footer
                        stream.append("0.7 0.7 0.7 RG 40 45 m 555 45 l S\n");
                        stream.append("BT /F1 7.5 Tf 0.4 0.4 0.4 rg 50 35 Td (")
                              .append(escape(raw.substring(2)))
                              .append(") Tj ET\n");
                    } else if (raw.startsWith("P:")) {
                        // Paragraph
                        stream.append("BT /F1 8 Tf 0.2 0.2 0.2 rg 50 ")
                              .append(y)
                              .append(" Td (")
                              .append(escape(raw.substring(2)))
                              .append(") Tj ET\n");
                        y -= 14;
                    }
                }

                byte[] streamBytes = stream.toString().getBytes(StandardCharsets.ISO_8859_1);

                // Object 6: Stream
                offsets.add(out.size());
                write(out, "6 0 obj\n<< /Length " + streamBytes.length + " >>\nstream\n");
                out.write(streamBytes);
                write(out, "\nendstream\nendobj\n");

                // Cross-Reference Table
                int xrefStart = out.size();
                write(out, "xref\n0 " + (offsets.size() + 1) + "\n");
                write(out, "0000000000 65535 f \n");
                for (int off : offsets) {
                    write(out, String.format("%010d 00000 n \n", off));
                }

                // Trailer
                write(out, "trailer\n<< /Size " + (offsets.size() + 1) + " /Root 1 0 R >>\n");
                write(out, "startxref\n" + xrefStart + "\n%%EOF\n");

                return out.toByteArray();
            } catch (IOException e) {
                return new byte[0];
            }
        }

        private void write(ByteArrayOutputStream out, String s) throws IOException {
            out.write(s.getBytes(StandardCharsets.ISO_8859_1));
        }

        private String escape(String s) {
            if (s == null) return "";
            return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)");
        }
    }
